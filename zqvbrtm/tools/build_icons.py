"""Build js/icons.js and js/art.js from two MIT-licensed icon packages.

    UI icons   Phosphor Icons (duotone, plus fill for active states)
               https://phosphoricons.com  -- npm @phosphor-icons/core
    3D art     Microsoft Fluent Emoji, 3D style (256px WebP)
               https://github.com/microsoft/fluentui-emoji
               -- npm @lobehub/fluent-emoji-3d

Nothing is fetched at run time: the SVG paths and the WebP images are
written into the two modules. To rebuild:

    npm pack @phosphor-icons/core @lobehub/fluent-emoji-3d
    tar -xzf phosphor-icons-core-*.tgz -C phosphor
    tar -xzf lobehub-fluent-emoji-3d-*.tgz -C fluent
    python3 tools/build_icons.py phosphor/package fluent/package
"""

