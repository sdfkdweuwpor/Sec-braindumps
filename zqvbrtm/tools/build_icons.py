def svg_inner(path):
    svg = Path(path).read_text()
    inner = re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S).group(1)
    # The duotone back layer gets a class so CSS can set its strength.
    inner = inner.replace(' opacity="0.2"', ' class="duo"')
    return inner.strip()


def js_string(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def build_icons(phosphor):
    assets = Path(phosphor) / 'assets'
    duo = {k: svg_inner(assets / 'duotone' / f'{v}-duotone.svg') for k, v in UI.items()}
    fill = {k: svg_inner(assets / 'fill' / f'{UI[k]}-fill.svg') for k in FILLED}
    lines = [
        '/**',
        ' * Icons: Phosphor Icons, duotone weight (a filled version too for the',
        ' * active tab and a pressed flag). MIT license, https://phosphoricons.com.',
        ' * Generated by tools/build_icons.py; edit that, not this file.',
        ' *',
        ' * Inline SVG on a 256 grid: crisp at any size, colored by the text color',
        ' * (the soft back layer, class "duo", is the same color at low strength),',
        ' * and no network requests.',
        ' */',
        '',
        'const DUO = {',
        *[f'  {k}: {js_string(v)},' for k, v in duo.items()],
        '};',
        '',
        'const FILL = {',
        *[f'  {k}: {js_string(v)},' for k, v in fill.items()],
        '};',
        '',
        '/** An icon. `weight: "fill"` picks the filled version where there is one. */',
        "export function icon(name, { size = 20, label = '', weight = 'duotone' } = {}) {",
        "  const span = document.createElement('span');",
        "  const filled = weight === 'fill' && FILL[name];",
        "  span.className = `icon icon-${name} w-${filled ? 'fill' : 'duo'}`;",
        "  if (label) { span.setAttribute('role', 'img'); span.setAttribute('aria-label', label); }",
        "  else span.setAttribute('aria-hidden', 'true');",
        '  const body = filled ? FILL[name] : (DUO[name] || DUO.empty);',
        '  span.innerHTML = `<svg viewBox="0 0 256 256" width="${size}" height="${size}" fill="currentColor" focusable="false">${body}</svg>`;',
        '  return span;',
        '}',
        '',
        '/**',
        ' * Both weights side by side; CSS shows the filled one when the control is',
        ' * current or pressed (see .icon-pair in app.css).',
        ' */',
        'export function iconPair(name, opts = {}) {',
        "  const span = document.createElement('span');",
        "  span.className = 'icon-pair';",
        "  span.setAttribute('aria-hidden', 'true');",
        "  span.append(icon(name, opts), icon(name, { ...opts, weight: 'fill' }));",
        '  return span;',
        '}',
        '',
    ]
    (ROOT / 'js' / 'icons.js').write_text('\n'.join(lines))


def build_art(fluent):
    assets = Path(fluent) / 'assets'
    data = {}
    for name, code in ART.items():
        raw = (assets / f'{code}.webp').read_bytes()
        data[name] = 'data:image/webp;base64,' + base64.b64encode(raw).decode()
    lines = [
        '/**',
        ' * 3D art for the big feature icons: Microsoft Fluent Emoji, 3D style.',
        ' * MIT license, https://github.com/microsoft/fluentui-emoji (WebP versions',
        ' * from npm @lobehub/fluent-emoji-3d). Generated by tools/build_icons.py.',
        ' *',
        ' * The images are embedded, so they work offline and need no extra files.',
        ' */',
        '',
        'const ART = {',
        *[f'  {k}: {js_string(v)},' for k, v in data.items()],
        '};',
        '',
        '/** Names of the available art. */',
        'export const ART_NAMES = Object.keys(ART);',
        '',
        '/** A 3D picture (decorative: screen readers skip it). */',
        'export function art(name, { size = 48 } = {}) {',
        "  const img = document.createElement('img');",
        "  img.className = `art art-${name}`;",
        '  img.src = ART[name] || ART.compass;',
        '  img.width = size;',
        '  img.height = size;',
        "  img.alt = '';",
        "  img.decoding = 'async';",
        "  img.draggable = false;",
        '  return img;',
        '}',
        '',
    ]
    (ROOT / 'js' / 'art.js').write_text('\n'.join(lines))


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    build_icons(sys.argv[1])
    build_art(sys.argv[2])
    print('wrote js/icons.js and js/art.js')
